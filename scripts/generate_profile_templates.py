#!/usr/bin/env python3
"""Generate bundled profile fields from one compact source configuration."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BACKEND = ROOT.parent / 'thoughtvault-backend/src/insanely_fast_whisper_api/app/profile_templates.py'
SOURCE = ROOT / 'data/profileBlueprints.json'


def build_entries(source):
    common = source['commonRules']
    entries = []
    for item in source['profiles']:
        sections = item['sections']
        prompt = f"{item['goal']} Inhoudsfocus: {item['focus']} Detailniveau: {item['detail']} Stijl: {item['style']}"
        if sections:
            prompt += " Gebruik deze secties in deze volgorde wanneer ze inhoud hebben: " + ', '.join(sections) + '.'
        else:
            prompt += " Geef alleen de prompt als doorlopende, kopieerbare tekst; geen vergadersecties. Verander de bedoeling niet."
        prompt += " Laat secties zonder inhoud weg.\n\nVormvoorbeeld:\n{{OUTPUT_TEMPLATE}}\n\nTranscriptie:\n{{TRANSCRIPTION}}"
        if sections:
            template = '<h1>[Beschrijvende titel]</h1>\n' + '\n'.join(
                f'<section><h2>{section}</h2><p>[Alleen brongebonden inhoud]</p></section>' for section in sections
            )
        else:
            template = '<h1>Prompt</h1>\n<p>[Kopieerbare prompttekst]</p>'
        entries.append({
            'id': item['id'], 'name': item['name'], 'description': item['description'], 'icon': item['icon'], 'emoji': item['emoji'],
            'systemPrompt': common, 'notulePrompt': prompt, 'template': template,
        })
    return entries


def outputs(entries):
    bundled = json.dumps(entries, ensure_ascii=False, indent=2) + '\n'
    definitions = {
        entry['id']: {**entry, 'outputTemplate': entry['template']} for entry in entries
    }
    for entry in definitions.values():
        del entry['id']
        del entry['template']
        entry['icon'] = entry.pop('emoji')
    backend = ('"""Generated by thoughtvault-native/scripts/generate_profile_templates.py.\n'
               'Edit data/profileBlueprints.json, then rerun the generator.\n"""\n\n'
               'import json\n\nPROFILE_DEFINITIONS = json.loads(' + repr(json.dumps(definitions, ensure_ascii=False)) + ')\n')
    targets = {
        ROOT / 'macos/Resources/ProfileTemplates.json': bundled,
        ROOT / 'windows/src/data/profileTemplates.json': bundled,
    }
    if BACKEND.parent.is_dir():
        targets[BACKEND] = backend
    return targets


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    entries = build_entries(json.loads(SOURCE.read_text()))
    stale = []
    for path, content in outputs(entries).items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path))
        else:
            path.write_text(content)
    if stale:
        parser.error('Generated files are stale: ' + ', '.join(stale))


if __name__ == '__main__':
    main()
